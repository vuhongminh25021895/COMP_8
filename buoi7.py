def binary_search(arr, value):
 left, right = 0, len(arr) - 1
 while left <= right:
  mid = (left + right) // 2
  if arr[mid] == value:
   return mid
  elif arr[mid] < value:
   left = mid + 1
  else:
   right = mid - 1
 return -1

arr = [1, 2, 3, 4, 5, 6]
value = 7
print(binary_search(arr, value))


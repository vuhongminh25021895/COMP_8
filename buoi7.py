def length(lst):
 n = len(lst)
 if n == 0:
  return 0
 dp = [1] * n
 for i in range(n):
  for j in range(i):
   if lst[j] < lst[i]:
    dp[i] = max(dp[i], dp[j] + 1)
 return max(dp)
lst = [0, 1, 0, 3, 2, 3]

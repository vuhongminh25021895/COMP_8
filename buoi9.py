def is_path_crossing(moves):
  x, y = 0, 0
  toado = set()
  toado.add((x, y))
  for move in moves:
    if move == 'R':
      x += 1
      if (x, y) in toado:
        return True
    elif move == 'L':
      x -= 1
      if (x, y) in toado:
        return True
    elif move == 'U':
      y += 1
      if (x, y) in toado:
        return True
    elif move == 'D':
      y -= 1
      if (x, y) in toado:
        return True
    toado.add((x, y))
  return False

def Median(nums):
 a, b, c, d, e = nums
 if a > b:
  a, b = b, a
 if c > d:
  c, d = d, c
 if a > c:
  a, c = c, a
  b, d = d, b
 if b > e:
  b, e = e, b
 if b > c:
  b, c = c, b
 if c > e:
  c, e = e, c
 return c
nums = [1, 10, 3, 8, 5]
print(Median(nums))

